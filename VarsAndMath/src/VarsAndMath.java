public class VarsAndMath {

    public static void main(String[] args) {

        // 1. Primitive-type variables
        int a = 5;
        int b = 6;
        double c = 7;

        // 2. Simple arithmetic
        int sum = a + b;
        int difference = a - b;
        double scaled = c * 20;

        // 3. String concatenation to display results
        System.out.println("a = " + a);
        System.out.println("b = " + b);
        System.out.println("c = " + c);

        System.out.println("The sum of a and b is " + sum);
        System.out.println("The difference (a - b) is " + difference);
        System.out.println("c multiplied by 20 is " + scaled);
    }
}

